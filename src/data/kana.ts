export const ALL_KANA: KanaChar[] = [...HIRAGANA, ...KATAKANA];

const kanaIndex = new Map(ALL_KANA.map((k) => [k.char, k]));

export function getKana(char: string): KanaChar | undefined {
  return kanaIndex.get(char);
}

export function kanaByChars(chars: string[]): KanaChar[] {
  return chars.map((c) => {
    const k = kanaIndex.get(c);
    if (!k) throw new Error(`Unknown kana: ${c}`);
    return k;
  });
}

/** Characters that only work as part of something else and shouldn't be quizzed as "read this sound". */
export function isQuizzableKana(k: KanaChar): boolean {
  return k.group !== "special" && k.char !== "を" && k.char !== "ヲ" && k.char !== "ぢ" && k.char !== "づ" && k.char !== "ヂ" && k.char !== "ヅ";
}

