import type { KanaChar, KanaGroup, Script } from "@/lib/types";

/**
 * Hiragana & Katakana reference data.
 * Thai pronunciation is an approximation for beginners; always pair it with romaji and audio.
 * Stroke guides are only provided for characters where the guide has been verified.
 */

type Ex = [word: string, romaji: string, meaning: string];
type Row = [char: string, romaji: string, thai: string, example?: Ex, mnemonic?: string];

function build(script: Script, group: KanaGroup, row: string, items: Row[]): KanaChar[] {
  return items.map(([char, romaji, thai, ex, mnemonic]) => ({
    char,
    romaji,
    thai,
    script,
    group,
    row,
    example: ex ? { word: ex[0], romaji: ex[1], meaning: ex[2] } : undefined,
    mnemonic,
  }));
}

